/**
 * 由学生姓名推导一个亲切的称呼，用于回访文案。
 *
 * 例：李一一 → 一一，李小明 → 小明，欧阳娜娜 → 娜娜，李一 → 李一（无法安全缩短）
 */

// 常见复姓（用于避免把「欧阳明」错切成「阳明」）
const COMPOUND_SURNAMES = [
  '欧阳', '太史', '端木', '上官', '司马', '东方', '独孤', '南宫', '万俟', '闻人',
  '夏侯', '诸葛', '尉迟', '公羊', '赫连', '澹台', '皇甫', '宗政', '濮阳', '公冶',
  '太叔', '申屠', '公孙', '慕容', '仲孙', '钟离', '长孙', '宇文', '司徒', '鲜于',
  '司空', '闾丘', '子车', '亓官', '司寇', '巫马', '公西', '颛孙', '壤驷', '公良',
  '漆雕', '乐正', '宰父', '谷梁', '拓跋', '夹谷', '轩辕', '令狐', '段干', '百里',
  '呼延', '东郭', '南门', '羊舌', '微生', '梁丘', '左丘', '西门', '第五', '公乘',
  '南荣', '东里', '仲长', '即墨', '达奚',
];

export function deriveNickname(name: string): string {
  const n = (name || '').trim();
  if (!n) return '';

  // 英文名 / 拼音：原样使用，已足够亲切
  if (/^[A-Za-z]/.test(n)) return n;

  // 复姓：去掉前两字（欧阳明 → 明，欧阳娜娜 → 娜娜）
  if (n.length >= 3 && COMPOUND_SURNAMES.includes(n.slice(0, 2))) {
    return n.slice(2);
  }

  // 三字及以上：去掉姓氏（李一一 → 一一，李小明 → 小明）
  if (n.length >= 3) return n.slice(1);

  // 两字名（李一）：去掉姓只剩一个字，既不够亲切也容易撞名，保持原样更稳妥
  return n;
}
